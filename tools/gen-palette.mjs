#!/usr/bin/env node
/* Generate the ayu palette blocks in the Sass sources from tools/palette.json.
 *
 *   node tools/gen-palette.mjs          # rewrite the generated blocks
 *   node tools/gen-palette.mjs --check  # fail if the blocks are out of date
 *
 * The palette comes from https://github.com/ayu-theme/ayu-colors
 * (themes/*.yaml, shipped as the npm package `ayu`). tools/palette.json is a
 * verbatim copy of the generated values; the Sass maps are generated from it
 * so the four theme variants can never drift apart.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const palette = JSON.parse(fs.readFileSync(path.join(ROOT, "tools/palette.json"), "utf8"));

const START = "// BEGIN AYU PALETTE (generated by tools/gen-palette.mjs from tools/palette.json)";
const END = "// END AYU PALETTE";

const TARGETS = [
  "common/gtk-3.0/3.22/sass/_colors.scss",
  "common/gtk-4.0/sass/_colors.scss",
  "common/cinnamon/sass/_colors.scss",
  "common/gnome-shell/3.22/sass/_ayu-palette.scss",
];

// Colors that are used by the theme but are not part of the ayu palette.
// They are generated from palette tokens (see PALETTE.md) and must be listed
// here so the checker can accept them.
const EXTRA = {};

/* 8-digit hex (#rrggbbaa) -> Sass rgba() call.
 * The alpha byte is the quantized form of the alpha declared in
 * themes/*.yaml (e.g. 0.15 -> 0x26), so round it back to two decimals. */
function sassValue(hex) {
  const h = hex.replace(/^#/, "").toLowerCase();
  if (h.length === 8) {
    const alpha = Math.round((parseInt(h.slice(6, 8), 16) / 255) * 100) / 100;
    return `rgba(#${h.slice(0, 6).toUpperCase()}, ${alpha})`;
  }
  return `#${h.toUpperCase()}`;
}

/* Flatten the nested ayu token tree into dotted keys: editor.selection.active */
function flatten(node, prefix = []) {
  const out = [];
  for (const [key, value] of Object.entries(node)) {
    if (value && typeof value === "object") out.push(...flatten(value, [...prefix, key]));
    else out.push([[...prefix, key].join("."), value]);
  }
  return out;
}

function renderFlavor(flavor) {
  const entries = flatten(palette.flavors[flavor]);
  const width = Math.max(...entries.map(([k]) => k.length));
  const lines = entries.map(
    ([key, value]) => `    '${key}':${" ".repeat(width - key.length + 1)}${sassValue(value)},`
  );
  return `  ${flavor}: (\n${lines.join("\n")}\n  )`;
}

function renderBlock() {
  const flavors = Object.keys(palette.flavors);
  return [
    START,
    "$ayu: (",
    flavors.map(renderFlavor).join(",\n"),
    ") !default;",
    END,
  ].join("\n");
}

const check = process.argv.includes("--check");
let failed = false;

for (const rel of TARGETS) {
  const file = path.join(ROOT, rel);
  const text = fs.readFileSync(file, "utf8");
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1) {
    console.error(`${rel}: missing generated palette markers`);
    failed = true;
    continue;
  }
  const next = text.slice(0, start) + renderBlock() + text.slice(end + END.length);
  if (next === text) continue;
  if (check) {
    console.error(`${rel}: generated palette block is out of date (run: node tools/gen-palette.mjs)`);
    failed = true;
  } else {
    fs.writeFileSync(file, next);
    console.log(`${rel}: palette block updated`);
  }
}

if (failed) process.exit(1);
if (!check) console.log("palette generated");
